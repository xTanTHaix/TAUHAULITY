"""Installation of the pre-commit credential gate.

The gate is a plain POSIX sh script because git executes hooks through sh on
every supported platform, including Git for Windows. It invokes the interpreter
that installed it with -c and delegates the decision to
tauhaulity.tools.git_sentinel, so the gate and pillar eleven always agree and a
future change to the scanner automatically applies to already installed hooks.

Three properties are load bearing:
  * paths are quoted with shlex.quote, so a project inside "My Projects" does
    not split into two shell words;
  * the directory that CONTAINS the tauhaulity package is embedded in the hook
    and prepended to sys.path by the payload. The interpreter recorded at install
    time may be a plain system Python with nothing installed in its
    site-packages, and without this a gate installed into an unrelated project
    would silently fail to import the scanner;
  * an unusable gate blocks the commit instead of passing it. A security tool
    that bricks the developer when it is misinstalled gets removed, but a gate
    that lets every secret through while claiming to protect the repository is a
    worse failure, so the default is fail closed and --warn-only is the explicit
    opt out that turns the same condition into a loud warning.
"""

from __future__ import annotations

import os
import shlex
import shutil
import sys
from pathlib import Path

GATE_MARKER = "# tauhaulity:pre-commit-gate"
BACKUP_SUFFIX = ".tauhaulity-backup"

# Python source executed through "python -c". It deliberately avoids single
# quotes so the whole payload can live inside one sh single quoted argument, and
# it avoids any shell interpolation so the repository path is the only variable.
_GATE_PAYLOAD = """import sys


def refuse(block, message):
    print("tauhaulity: " + message, file=sys.stderr)
    if block:
        print("tauhaulity: commit blocked because the secret gate is not operational", file=sys.stderr)
        sys.exit(1)
    print("tauhaulity: commit allowed because the gate was installed with --warn-only", file=sys.stderr)
    sys.exit(0)


root = sys.argv[1]
block = sys.argv[2] == "1"
package_root = sys.argv[3] if len(sys.argv) > 3 else ""

# The recorded interpreter may have no tauhaulity in its site-packages. The
# embedded package root is the directory that contains the tauhaulity package,
# so a gate installed from a development checkout also works in another project.
if package_root:
    sys.path.insert(0, package_root)
try:
    from tauhaulity.tools.git_sentinel import scan_staged
except Exception as first_error:
    sys.path.insert(0, root)
    try:
        from tauhaulity.tools.git_sentinel import scan_staged
    except Exception:
        refuse(block, "secret gate unavailable: " + type(first_error).__name__ + ": " + str(first_error))
try:
    from pathlib import Path
    raw_hits = scan_staged(Path(root))
except Exception as scan_error:
    refuse(block, "secret scan failed: " + type(scan_error).__name__ + ": " + str(scan_error))

# Accepted candidates recorded by "tauhaulity baseline" must not block every
# future commit that touches the same file, or the gate becomes unusable and gets
# removed. A genuinely new candidate is still reported and still blocks. A
# missing or broken baseline suppresses nothing.
suppressed = 0
hits = raw_hits
try:
    from tauhaulity.tools.allowlist import filter_hits, load_baseline
    hits, suppressed = filter_hits(raw_hits, load_baseline(Path(root)))
except Exception:
    hits = raw_hits
if suppressed:
    print("tauhaulity: " + str(suppressed) + " accepted credential candidate(s) suppressed by the baseline", file=sys.stderr)
for hit in hits:
    print("tauhaulity: " + hit.kind + " secret in " + hit.rel_path + ":" + str(hit.line_no) + " -> " + hit.masked, file=sys.stderr)
if hits and block:
    print("tauhaulity: commit blocked; " + str(len(hits)) + " credential candidate(s) staged", file=sys.stderr)
    print("tauhaulity: remove the secret or reinstall with --no-block to record only", file=sys.stderr)
    sys.exit(1)
sys.exit(0)
"""

_SCRIPT_TEMPLATE = """#!/bin/sh
""" + GATE_MARKER + """
# Generated by tauhaulity.tools.hook_installer. Reinstall with:
#   tauhaulity hook install [--no-block]
# The interpreter recorded below is the one that installed the gate, because a
# project may run against a specific Python installation with tauhaulity
# importable. subtle quoting: TAUHAULITY_ROOT is already shlex quoted.
TAUHAULITY_ROOT=@ROOT@
TAUHAULITY_PYTHON=@PYTHON@
TAUHAULITY_BLOCK=@BLOCK@
TAUHAULITY_PACKAGE_ROOT=@PACKAGE_ROOT@

# Git for Windows hands us native Windows paths; cygpath translates them into
# the POSIX view the shell can execute.
if command -v cygpath >/dev/null 2>&1; then
    TAUHAULITY_POSIX=$(cygpath -u "$TAUHAULITY_PYTHON" 2>/dev/null)
    if [ -n "$TAUHAULITY_POSIX" ]; then
        TAUHAULITY_PYTHON="$TAUHAULITY_POSIX"
    fi
fi

run_gate() {
    "$TAUHAULITY_PYTHON" -c '@PAYLOAD@' "$TAUHAULITY_ROOT" "$TAUHAULITY_BLOCK" "$TAUHAULITY_PACKAGE_ROOT"
}

if [ -x "$TAUHAULITY_PYTHON" ]; then
    run_gate
    exit $?
fi

for candidate in python3 python; do
    if command -v "$candidate" >/dev/null 2>&1; then
        TAUHAULITY_PYTHON="$candidate"
        run_gate
        exit $?
    fi
done

if [ "$TAUHAULITY_BLOCK" = "1" ]; then
    echo "tauhaulity: no usable Python interpreter found; commit blocked because the secret gate is not operational" >&2
    echo "tauhaulity: install a Python that can import tauhaulity, or reinstall with --no-block to record only" >&2
    exit 1
fi

echo "tauhaulity: no usable Python interpreter found; secret gate skipped (installed with --warn-only)" >&2
exit 0
"""


def package_root() -> Path:
    """Return the directory that contains the importable tauhaulity package.

    The value is derived from the imported package object rather than from
    __file__ arithmetic alone, so a plain checkout, an editable install and a
    regular site-packages install all resolve to the directory that must be
    prepended to sys.path. When the package cannot be imported for any reason the
    source layout is used, which is always correct for this very module.
    """

    try:
        import tauhaulity

        module_file = getattr(tauhaulity, "__file__", None)
        if module_file:
            return Path(module_file).resolve().parent.parent
    except (ImportError, OSError, AttributeError, ValueError):
        pass
    return Path(__file__).resolve().parents[2]


class HookError(RuntimeError):
    """Raised when a repository has no git metadata to install a hook into."""


def _repository_git_dir(root: Path) -> Path | None:
    """Resolve the git metadata directory using the shared repository helper."""

    from tauhaulity.tools.git_sentinel import git_dir

    return git_dir(root)


def render_hook_script(root: Path, *, block: bool = True) -> str:
    """Render the pre-commit script for a project root.

    Parameters:
        root: Absolute project root the gate will scan.
        block: True aborts the commit on a hit, False only reports it.

    Returns:
        The complete POSIX sh script text with quoted paths and payload.
    """

    resolved = Path(root).resolve()
    return (
        _SCRIPT_TEMPLATE.replace("@ROOT@", shlex.quote(str(resolved)))
        .replace("@PYTHON@", shlex.quote(str(Path(sys.executable).resolve())))
        .replace("@BLOCK@", shlex.quote("1" if block else "0"))
        .replace("@PACKAGE_ROOT@", shlex.quote(str(package_root())))
        .replace("@PAYLOAD@", _GATE_PAYLOAD)
    )


def _hook_path(root: Path) -> Path:
    """Return the conventional hook path, even when git metadata is missing."""

    directory = _repository_git_dir(root)
    if directory is None:
        return Path(root) / ".git" / "hooks" / "pre-commit"
    return directory / "hooks" / "pre-commit"


def _is_our_hook(path: Path) -> bool:
    """Return True when the file carries our marker and payload reference."""

    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False
    if GATE_MARKER not in text:
        return False
    return "tauhaulity.tools.git_sentinel" in text


def install_hook(root: Path, *, block: bool = True) -> Path:
    """Write the pre-commit gate into the repository hooks directory.

    An existing third party hook is preserved as pre-commit.tauhaulity-backup
    before it is replaced: silently deleting another tool's hook is exactly the
    kind of surprise that makes developers uninstall a guard.

    Parameters:
        root: Project root containing the repository.
        block: Whether the gate aborts a commit on a detected credential.

    Returns:
        The path of the installed hook.

    Raises:
        HookError: When the directory is not a git work tree.
    """

    root = Path(root)
    directory = _repository_git_dir(root)
    if directory is None:
        raise HookError("no git repository found under " + str(root))
    hooks = directory / "hooks"
    try:
        hooks.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        raise HookError("cannot create hooks directory " + str(hooks) + ": " + str(exc)) from exc
    hook = hooks / "pre-commit"
    if hook.is_file() and not _is_our_hook(hook):
        backup = hooks / ("pre-commit" + BACKUP_SUFFIX)
        if not backup.exists():
            try:
                shutil.copy2(hook, backup)
            except OSError as exc:
                raise HookError("cannot back up existing hook " + str(hook) + ": " + str(exc)) from exc
    script = render_hook_script(root, block=block)
    try:
        with hook.open("w", encoding="utf-8", newline="\n") as handle:
            handle.write(script)
    except OSError as exc:
        raise HookError("cannot write hook " + str(hook) + ": " + str(exc)) from exc
    # chmod is meaningless on Windows for executable bits, but git on POSIX
    # refuses to run a non executable hook, so it must be attempted everywhere
    # and must never fail the installation on a filesystem that cannot store it.
    try:
        os.chmod(hook, 0o755)
    except OSError:
        pass
    return hook


def uninstall_hook(root: Path) -> bool:
    """Remove our gate and restore the previous hook if one was displaced.

    Parameters:
        root: Project root containing the repository.

    Returns:
        True when a gate installed by tauhaulity was removed.
    """

    root = Path(root)
    directory = _repository_git_dir(root)
    if directory is None:
        return False
    hook = directory / "hooks" / "pre-commit"
    if not hook.is_file() or not _is_our_hook(hook):
        return False
    try:
        hook.unlink()
    except OSError:
        return False
    backup = directory / "hooks" / ("pre-commit" + BACKUP_SUFFIX)
    if backup.is_file():
        try:
            os.replace(backup, hook)
            os.chmod(hook, 0o755)
        except OSError:
            # Restoring the third party hook is best effort: the important
            # guarantee is that our gate is gone.
            pass
    return True


def hook_status(root: Path) -> tuple[bool, Path]:
    """Report whether our gate is installed and where it lives.

    Parameters:
        root: Project root containing the repository.

    Returns:
        A (installed, path) pair; the path is the conventional location even when
        no repository metadata exists, so the dossier can always print it.
    """

    path = _hook_path(Path(root))
    if not path.is_file():
        return False, path
    return _is_our_hook(path), path
