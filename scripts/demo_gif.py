"""A dependency free GIF89a writer and reader, plus LZW compression.

The demo GIF that ships with the repository is generated by this module, so it
has to be a real GIF: header, logical screen descriptor, global colour table,
graphic control extension per frame with its delay, LZW compressed image data and
a trailer. Reading the frames back is part of the contract, because a generator
that cannot verify its own output is guessing.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Final, Iterable

GIF_HEADER: Final[bytes] = b"GIF89a"
BLOCK_EXTENSION: Final[int] = 0x21
BLOCK_IMAGE: Final[int] = 0x2C
BLOCK_TRAILER: Final[int] = 0x3B
SUB_GRAPHIC_CONTROL: Final[int] = 0xF9
SUB_APPLICATION: Final[int] = 0xFF
MAX_SUB_BLOCK: Final[int] = 255
MAX_CODE: Final[int] = 4096


class GifError(ValueError):
    """Raised when a GIF cannot be encoded or decoded."""


def palette_bits(entries: int) -> int:
    """Return the exponent of the smallest power of two holding the palette.

    A GIF logical screen descriptor encodes the global colour table size as
    "2 ** (field + 1)", so the encoder has to know the exponent, not the entry
    count.

    Raises:
        GifError: When the entry count is outside the two to 256 range.
    """

    if entries < 2 or entries > 256:
        raise GifError("palette must hold between two and 256 colours")
    exponent = 1
    while (1 << exponent) < entries:
        exponent += 1
    return exponent


def colour_table_entries(entries: int) -> int:
    """Return the padded global colour table size for a palette."""

    return 1 << palette_bits(entries)


def image_code_size(entries: int) -> int:
    """Return the LZW minimum code size that matches the colour table.

    The GIF specification requires at least two bits even for a monochrome
    image, which is why the exponent is raised to two.

    Raises:
        GifError: When the entry count is outside the two to 256 range.
    """

    return max(2, palette_bits(entries))


class _BitWriter:
    """Least significant bit first bit packer used by the LZW encoder."""

    def __init__(self) -> None:
        self._data = bytearray()
        self._accumulator = 0
        self._bits = 0

    def write(self, value: int, width: int) -> None:
        """Append a code of the given bit width."""

        if width <= 0 or width > 16:
            raise GifError(f"bit width {width} is out of range")
        self._accumulator |= (value & ((1 << width) - 1)) << self._bits
        self._bits += width
        while self._bits >= 8:
            self._data.append(self._accumulator & 0xFF)
            self._accumulator >>= 8
            self._bits -= 8

    def flush(self) -> None:
        """Emit any remaining partial byte."""

        if self._bits:
            self._data.append(self._accumulator & 0xFF)
            self._accumulator = 0
            self._bits = 0

    @property
    def data(self) -> bytes:
        """The packed bytes written so far."""

        return bytes(self._data)


def lzw_encode(indices: bytes, min_code_size: int) -> bytes:
    """Compress palette indices with the GIF LZW variant.

    Parameters:
        indices: One byte per pixel, each below 2 ** min_code_size.
        min_code_size: Bits per pixel, at least two as the format requires.

    Returns:
        The compressed byte stream, before sub block framing.

    Raises:
        GifError: When the code size is invalid or a pixel is out of range.
    """

    if min_code_size < 2 or min_code_size > 8:
        raise GifError("min_code_size must be between two and eight")
    clear_code = 1 << min_code_size
    end_code = clear_code + 1
    limit = 1 << min_code_size
    if any(index >= (1 << min_code_size) for index in indices):
        raise GifError("pixel index exceeds the palette size")

    writer = _BitWriter()
    code_size = min_code_size + 1
    table: dict[bytes, int] = {bytes([value]): value for value in range(limit)}
    next_code = end_code + 1
    writer.write(clear_code, code_size)

    buffer = b""
    for index in indices:
        candidate = buffer + bytes([index])
        if candidate in table:
            buffer = candidate
            continue
        writer.write(table[buffer], code_size)
        if next_code < MAX_CODE:
            table[candidate] = next_code
            next_code += 1
            if next_code == (1 << code_size) and code_size < 12:
                code_size += 1
        else:
            writer.write(clear_code, code_size)
            table = {bytes([value]): value for value in range(limit)}
            next_code = end_code + 1
            code_size = min_code_size + 1
        buffer = bytes([index])
    if buffer:
        writer.write(table[buffer], code_size)
    writer.write(end_code, code_size)
    writer.flush()
    return writer.data


class _BitReader:
    """Least significant bit first bit reader used by the LZW decoder."""

    def __init__(self, data: bytes) -> None:
        self._data = data
        self._position = 0
        self._accumulator = 0
        self._bits = 0

    def read(self, width: int) -> int | None:
        """Read one code, or None when the stream is exhausted."""

        while self._bits < width:
            if self._position >= len(self._data):
                return None
            self._accumulator |= self._data[self._position] << self._bits
            self._position += 1
            self._bits += 8
        value = self._accumulator & ((1 << width) - 1)
        self._accumulator >>= width
        self._bits -= width
        return value


def lzw_decode(data: bytes, min_code_size: int) -> bytes:
    """Decode a GIF LZW stream; used by the tests to prove the encoder.

    Raises:
        GifError: When the stream is malformed.
    """

    clear_code = 1 << min_code_size
    end_code = clear_code + 1
    reader = _BitReader(data)
    table: list[bytes] = [bytes([value]) for value in range(clear_code)] + [b"", b""]
    code_size = min_code_size + 1
    output = bytearray()
    previous = b""
    while True:
        code = reader.read(code_size)
        if code is None:
            break
        if code == clear_code:
            table = [bytes([value]) for value in range(clear_code)] + [b"", b""]
            code_size = min_code_size + 1
            previous = b""
            continue
        if code == end_code:
            break
        if code < len(table) and table[code]:
            entry = table[code]
        elif code == len(table) and previous:
            entry = previous + previous[:1]
        else:
            raise GifError(f"invalid LZW code {code}")
        output.extend(entry)
        if previous:
            table.append(previous + entry[:1])
            # The decoder builds its table one code behind the encoder, so its
            # threshold is one lower: the encoder widens when the next free code
            # reaches 1 << size, the decoder when its table reaches that minus one.
            if len(table) == (1 << code_size) - 1 and code_size < 12:
                code_size += 1
        previous = entry
    return bytes(output)


@dataclass(frozen=True, slots=True)
class Frame:
    """One animation frame.

    Attributes:
        indices: Palette indices, one byte per pixel, row major.
        delay_cs: Display time in hundredths of a second.
    """

    indices: bytes
    delay_cs: int


def _sub_blocks(payload: bytes) -> bytes:
    """Frame a byte string as GIF sub blocks."""

    out = bytearray()
    for offset in range(0, len(payload), MAX_SUB_BLOCK):
        chunk = payload[offset : offset + MAX_SUB_BLOCK]
        out.append(len(chunk))
        out.extend(chunk)
    out.append(0)
    return bytes(out)


def _changed_box(
    previous: bytes,
    current: bytes,
    width: int,
    height: int,
) -> tuple[int, int, int, int] | None:
    """Return the smallest rectangle covering pixels that changed.

    Parameters:
        previous: Previous full canvas indices.
        current: Current full canvas indices.
        width: Canvas width.
        height: Canvas height.

    Returns:
        (left, top, box_width, box_height) or None when nothing changed. Only the
        rows that differ are scanned in detail, so a settled terminal costs a
        couple of thousand comparisons instead of a megabyte.
    """

    top = -1
    bottom = -1
    left = width
    right = -1
    for y in range(height):
        base = y * width
        if previous[base : base + width] == current[base : base + width]:
            continue
        if top < 0:
            top = y
        bottom = y
        for x in range(width):
            if previous[base + x] != current[base + x]:
                if x < left:
                    left = x
                break
        for x in range(width - 1, -1, -1):
            if previous[base + x] != current[base + x]:
                if x > right:
                    right = x
                break
    if top < 0 or right < left:
        return None
    return left, top, right - left + 1, bottom - top + 1


def _extract_box(indices: bytes, width: int, left: int, top: int, box_width: int, box_height: int) -> bytes:
    """Copy a rectangle out of a row major full canvas."""

    out = bytearray()
    for y in range(top, top + box_height):
        base = y * width + left
        out.extend(indices[base : base + box_width])
    return bytes(out)


def encode_gif(
    frames: Iterable[Frame],
    width: int,
    height: int,
    palette: tuple[tuple[int, int, int], ...],
    *,
    loop: bool = True,
    optimise: bool = True,
) -> bytes:
    """Encode an animated GIF89a.

    Parameters:
        frames: Frames in display order; each must match width * height.
        width: Image width in pixels.
        height: Image height in pixels.
        palette: Colours, at most 256 entries; the table is padded to a power of
            two as the format requires.
        loop: Emit the Netscape looping extension.
        optimise: When true each image descriptor covers only the rectangle that
            changed since the previous frame. Disposal is left at zero, so the
            decoder keeps the untouched pixels; this is what keeps a mostly
            static terminal animation well under the size budget. Decoded frames
            are always recomposed to the full canvas.

    Returns:
        The complete GIF file bytes.

    Raises:
        GifError: When the palette or a frame is unusable.
    """

    # The size field in the packed byte encodes 2 ** (field + 1) entries, so a
    # two colour palette needs field 0, not field 1.
    exponent = palette_bits(len(palette))
    entries = 1 << exponent
    size_field = exponent - 1
    min_code_size = image_code_size(len(palette))
    table = bytearray()
    for colour in palette:
        if any(component < 0 or component > 255 for component in colour):
            raise GifError("palette component out of range")
        table.extend(colour)
    table.extend(b"\x00" * (entries * 3 - len(table)))

    out = bytearray(GIF_HEADER)
    out.extend(int(width).to_bytes(2, "little"))
    out.extend(int(height).to_bytes(2, "little"))
    # Global colour table present, colour resolution 8 bits, size exponent.
    out.append(0x80 | 0x70 | size_field)
    out.append(0)
    out.append(0)
    out.extend(table)
    if loop:
        out.extend(bytes([BLOCK_EXTENSION, SUB_APPLICATION, 0x0B]))
        out.extend(b"NETSCAPE2.0")
        out.extend(bytes([0x03, 0x01, 0x00, 0x00, 0x00]))

    seen = 0
    previous = bytes(width * height)
    for frame in frames:
        if len(frame.indices) != width * height:
            raise GifError("frame size does not match the canvas")
        if frame.delay_cs < 0:
            raise GifError("frame delay must not be negative")
        if optimise:
            box = _changed_box(previous, frame.indices, width, height)
            if box is None:
                # A static frame still needs a delay; a one pixel image with the
                # existing colour changes no visible pixel and costs one code.
                left, top, box_width, box_height = 0, 0, 1, 1
                pixels = bytes([frame.indices[0]])
            else:
                left, top, box_width, box_height = box
                pixels = _extract_box(frame.indices, width, left, top, box_width, box_height)
        else:
            left, top, box_width, box_height = 0, 0, width, height
            pixels = frame.indices
        out.extend(bytes([BLOCK_EXTENSION, SUB_GRAPHIC_CONTROL, 0x04]))
        out.append(0x00)
        out.extend(int(frame.delay_cs).to_bytes(2, "little"))
        out.append(0)
        out.append(0)
        out.append(BLOCK_IMAGE)
        out.extend(int(left).to_bytes(2, "little"))
        out.extend(int(top).to_bytes(2, "little"))
        out.extend(int(box_width).to_bytes(2, "little"))
        out.extend(int(box_height).to_bytes(2, "little"))
        out.append(0)  # no local colour table
        out.append(min_code_size)
        out.extend(_sub_blocks(lzw_encode(pixels, min_code_size)))
        previous = frame.indices
        seen += 1
    if seen == 0:
        raise GifError("at least one frame is required")
    out.append(BLOCK_TRAILER)
    return bytes(out)


def decode_gif(data: bytes) -> tuple[int, int, tuple[tuple[int, int, int], ...], list[Frame]]:
    """Decode a GIF produced by encode_gif.

    Returns:
        width, height, palette and the decoded frames.

    Raises:
        GifError: When the file is not a single image per frame GIF89a.
    """

    if not data.startswith(GIF_HEADER):
        raise GifError("not a GIF89a file")
    position = 6
    width = int.from_bytes(data[position : position + 2], "little")
    height = int.from_bytes(data[position + 2 : position + 4], "little")
    packed = data[position + 4]
    position += 7
    palette: list[tuple[int, int, int]] = []
    if packed & 0x80:
        bits = (packed & 0x07) + 1
        count = 1 << bits
        for index in range(count):
            base = position + index * 3
            palette.append((data[base], data[base + 1], data[base + 2]))
        position += count * 3
    delay = 0
    frames: list[Frame] = []
    composite = bytearray(width * height)
    while position < len(data):
        marker = data[position]
        position += 1
        if marker == BLOCK_TRAILER:
            break
        if marker == BLOCK_EXTENSION:
            label = data[position]
            position += 1
            if label == SUB_GRAPHIC_CONTROL:
                size = data[position]
                position += 1
                delay = int.from_bytes(data[position + 1 : position + 3], "little")
                position += size
                position += 1
                continue
            while True:
                size = data[position]
                position += 1
                if size == 0:
                    break
                position += size
            continue
        if marker != BLOCK_IMAGE:
            raise GifError(f"unexpected block 0x{marker:02X}")
        left = int.from_bytes(data[position : position + 2], "little")
        top = int.from_bytes(data[position + 2 : position + 4], "little")
        image_width = int.from_bytes(data[position + 4 : position + 6], "little")
        image_height = int.from_bytes(data[position + 6 : position + 8], "little")
        position += 8
        if left + image_width > width or top + image_height > height:
            raise GifError("image descriptor falls outside the logical screen")
        local_packed = data[position]
        position += 1
        if local_packed & 0x80:
            local_bits = (local_packed & 0x07) + 1
            position += (1 << local_bits) * 3
        image_code_size = data[position]
        position += 1  # LZW minimum code size
        chunks = bytearray()
        while True:
            size = data[position]
            position += 1
            if size == 0:
                break
            chunks.extend(data[position : position + size])
            position += size
        pixels = lzw_decode(bytes(chunks), max(2, image_code_size))
        if len(pixels) != image_width * image_height:
            raise GifError("image data does not match its descriptor")
        # Disposal zero keeps the previous pixels, so the decoder recomposes the
        # full canvas here; callers always receive complete frames.
        for row in range(image_height):
            source = row * image_width
            target = (top + row) * width + left
            composite[target : target + image_width] = pixels[source : source + image_width]
        frames.append(Frame(indices=bytes(composite), delay_cs=delay))
        delay = 0
    return width, height, tuple(palette), frames
